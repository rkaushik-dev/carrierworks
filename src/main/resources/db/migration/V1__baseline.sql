-- The bench as it stood when the database was introduced: boards, their slots and state,
-- leases, jobs, the image registry, build provenance and build reports. Tables are created in
-- dependency order.

CREATE TABLE boards (
    tag               VARCHAR(12)  NOT NULL,
    model             VARCHAR(64)  NOT NULL,
    revision          VARCHAR(8)   DEFAULT 'a' NOT NULL,
    part              VARCHAR(32)  NOT NULL,
    device            VARCHAR(16)  NOT NULL,
    flash             VARCHAR(32)  NOT NULL,
    rack              VARCHAR(64)  NOT NULL,
    shelf             INTEGER      NOT NULL,
    slot              INTEGER      NOT NULL,
    adapter_serial    VARCHAR(16),
    adapter_model     VARCHAR(64),
    adapter_port      VARCHAR(64)  DEFAULT '' NOT NULL,
    pdu               VARCHAR(64),
    outlet            INTEGER,
    vadj_millivolts   INTEGER      DEFAULT 1800 NOT NULL,
    header_voltage_mv INTEGER      DEFAULT 1800 NOT NULL,
    max_tck_hz        INTEGER      DEFAULT 30000000 NOT NULL,
    notes             VARCHAR(240) DEFAULT '' NOT NULL,
    CONSTRAINT pk_boards PRIMARY KEY (tag),
    CONSTRAINT uq_boards_location UNIQUE (rack, shelf, slot),
    CONSTRAINT uq_boards_adapter UNIQUE (adapter_serial),
    CONSTRAINT uq_boards_outlet UNIQUE (pdu, outlet),
    CONSTRAINT ck_boards_shelf CHECK (shelf BETWEEN 1 AND 12),
    CONSTRAINT ck_boards_slot CHECK (slot BETWEEN 1 AND 6),
    CONSTRAINT ck_boards_tck CHECK (max_tck_hz > 0)
);
CREATE INDEX ix_boards_model ON boards (model);
CREATE INDEX ix_boards_device ON boards (device);

CREATE TABLE board_slots (
    id        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    board_tag VARCHAR(12) NOT NULL,
    name      VARCHAR(64) NOT NULL,
    connector VARCHAR(64) NOT NULL,
    fitted    VARCHAR(64),
    CONSTRAINT pk_board_slots PRIMARY KEY (id),
    CONSTRAINT fk_board_slots_board_tag FOREIGN KEY (board_tag) REFERENCES boards (tag) ON DELETE CASCADE,
    CONSTRAINT uq_slots_name UNIQUE (board_tag, name)
);
CREATE INDEX ix_slots_fitted ON board_slots (fitted);

CREATE TABLE board_states (
    board_tag    VARCHAR(12)  NOT NULL,
    state        VARCHAR(16)  NOT NULL,
    since        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    reason       VARCHAR(240) DEFAULT '' NOT NULL,
    actor        VARCHAR(64)  DEFAULT '' NOT NULL,
    is_available BOOLEAN      DEFAULT TRUE NOT NULL,
    CONSTRAINT pk_board_states PRIMARY KEY (board_tag),
    CONSTRAINT fk_board_states_board_tag FOREIGN KEY (board_tag) REFERENCES boards (tag) ON DELETE CASCADE,
    CONSTRAINT ck_board_states_state CHECK (LENGTH(state) > 0)
);
CREATE INDEX ix_board_states_state ON board_states (state);

-- One board can have any number of closed leases and at most one open one. open_board_tag
-- holds the board only while the lease is open, so a unique index over it lets closed leases
-- pile up (their value is null) and refuses a second open lease on the same board.
CREATE TABLE leases (
    id             VARCHAR(24)  NOT NULL,
    board_tag      VARCHAR(12)  NOT NULL,
    holder         VARCHAR(64)  NOT NULL,
    purpose        VARCHAR(240) NOT NULL,
    taken_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    expires_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    priority       INTEGER      DEFAULT 5 NOT NULL,
    renewals       INTEGER      DEFAULT 0 NOT NULL,
    preemptible    BOOLEAN      DEFAULT TRUE NOT NULL,
    released_at    TIMESTAMP(6) WITH TIME ZONE,
    release_reason VARCHAR(120) DEFAULT '' NOT NULL,
    open_board_tag VARCHAR(12) GENERATED ALWAYS AS (CASE WHEN released_at IS NULL THEN board_tag END),
    CONSTRAINT pk_leases PRIMARY KEY (id),
    CONSTRAINT fk_leases_board_tag FOREIGN KEY (board_tag) REFERENCES boards (tag) ON DELETE RESTRICT,
    CONSTRAINT ck_leases_priority CHECK (priority BETWEEN 1 AND 9),
    CONSTRAINT ck_leases_window CHECK (expires_at > taken_at)
);
CREATE UNIQUE INDEX uq_leases_active_board ON leases (open_board_tag);
CREATE INDEX ix_leases_holder ON leases (holder);
CREATE INDEX ix_leases_taken_at ON leases (taken_at);

CREATE TABLE jobs (
    id           VARCHAR(24)  NOT NULL,
    board_tag    VARCHAR(12)  NOT NULL,
    digest       VARCHAR(64)  NOT NULL,
    mode         VARCHAR(16)  NOT NULL,
    requested_by VARCHAR(64)  NOT NULL,
    state        VARCHAR(16)  DEFAULT 'queued' NOT NULL,
    attempts     INTEGER      DEFAULT 0 NOT NULL,
    verify       BOOLEAN      DEFAULT TRUE NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    started_at   TIMESTAMP(6) WITH TIME ZONE,
    finished_at  TIMESTAMP(6) WITH TIME ZONE,
    not_before   TIMESTAMP(6) WITH TIME ZONE,
    error        VARCHAR(240) DEFAULT '' NOT NULL,
    error_code   VARCHAR(32)  DEFAULT '' NOT NULL,
    clocks       INTEGER      DEFAULT 0 NOT NULL,
    lease_id     VARCHAR(24),
    CONSTRAINT pk_jobs PRIMARY KEY (id),
    CONSTRAINT fk_jobs_board_tag FOREIGN KEY (board_tag) REFERENCES boards (tag) ON DELETE RESTRICT,
    CONSTRAINT ck_jobs_attempts CHECK (attempts >= 0),
    CONSTRAINT ck_jobs_digest CHECK (LENGTH(digest) = 64)
);
CREATE INDEX ix_jobs_board_state ON jobs (board_tag, state);
CREATE INDEX ix_jobs_digest ON jobs (digest);
CREATE INDEX ix_jobs_created_at ON jobs (created_at);

CREATE TABLE artifacts (
    digest       VARCHAR(64)  NOT NULL,
    design       VARCHAR(64)  NOT NULL,
    device       VARCHAR(16)  NOT NULL,
    length_bytes INTEGER      NOT NULL,
    kind         VARCHAR(8)   NOT NULL,
    channel      VARCHAR(16)  DEFAULT 'dev' NOT NULL,
    source       VARCHAR(64)  DEFAULT '' NOT NULL,
    tool_version VARCHAR(32)  DEFAULT '' NOT NULL,
    stored_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    tags         VARCHAR(240) DEFAULT '' NOT NULL,
    CONSTRAINT pk_artifacts PRIMARY KEY (digest),
    CONSTRAINT ck_artifacts_digest CHECK (LENGTH(digest) = 64),
    CONSTRAINT ck_artifacts_length CHECK (length_bytes > 0)
);
CREATE INDEX ix_artifacts_design ON artifacts (design);
CREATE INDEX ix_artifacts_channel ON artifacts (channel);
CREATE INDEX ix_artifacts_device ON artifacts (device);

-- Several builds can produce the same image, so the key is the pair rather than the digest.
CREATE TABLE provenance (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY,
    digest             VARCHAR(64) NOT NULL,
    design             VARCHAR(64) NOT NULL,
    source_revision    VARCHAR(40) NOT NULL,
    build_id           VARCHAR(64) NOT NULL,
    built_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    tool_version       VARCHAR(32) DEFAULT '' NOT NULL,
    constraints_digest VARCHAR(64) DEFAULT '' NOT NULL,
    builder            VARCHAR(64) DEFAULT '' NOT NULL,
    branch             VARCHAR(64) DEFAULT '' NOT NULL,
    dirty              BOOLEAN     DEFAULT FALSE NOT NULL,
    CONSTRAINT pk_provenance PRIMARY KEY (id),
    CONSTRAINT fk_provenance_digest FOREIGN KEY (digest) REFERENCES artifacts (digest) ON DELETE CASCADE,
    CONSTRAINT uq_provenance_build UNIQUE (digest, build_id)
);
CREATE INDEX ix_provenance_revision ON provenance (source_revision);

CREATE TABLE build_reports (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY,
    digest        VARCHAR(64) NOT NULL,
    design        VARCHAR(64) NOT NULL,
    read_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    wns_ps        INTEGER NOT NULL,
    tns_ps        INTEGER NOT NULL,
    setup_failing INTEGER DEFAULT 0 NOT NULL,
    setup_total   INTEGER DEFAULT 0 NOT NULL,
    whs_ps        INTEGER NOT NULL,
    ths_ps        INTEGER NOT NULL,
    hold_failing  INTEGER DEFAULT 0 NOT NULL,
    hold_total    INTEGER DEFAULT 0 NOT NULL,
    luts          INTEGER DEFAULT 0 NOT NULL,
    registers     INTEGER DEFAULT 0 NOT NULL,
    block_ram     INTEGER DEFAULT 0 NOT NULL,
    dsp           INTEGER DEFAULT 0 NOT NULL,
    is_baseline   BOOLEAN DEFAULT FALSE NOT NULL,
    CONSTRAINT pk_build_reports PRIMARY KEY (id),
    CONSTRAINT fk_build_reports_digest FOREIGN KEY (digest) REFERENCES artifacts (digest) ON DELETE CASCADE,
    CONSTRAINT uq_build_reports_digest UNIQUE (digest),
    CONSTRAINT ck_reports_setup_failing CHECK (setup_failing >= 0),
    CONSTRAINT ck_reports_hold_failing CHECK (hold_failing >= 0)
);
CREATE INDEX ix_build_reports_design ON build_reports (design);
