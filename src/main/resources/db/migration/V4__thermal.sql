-- Keep the temperature readings instead of throwing them away.

CREATE TABLE thermal_samples (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY,
    board        VARCHAR(12) NOT NULL,
    at           TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    millidegrees INTEGER NOT NULL,
    source       VARCHAR(16) DEFAULT 'sysmon' NOT NULL,
    CONSTRAINT pk_thermal_samples PRIMARY KEY (id),
    CONSTRAINT fk_thermal_samples_board FOREIGN KEY (board) REFERENCES boards (tag) ON DELETE CASCADE,
    CONSTRAINT ck_thermal_range CHECK (millidegrees BETWEEN -60000 AND 200000)
);
CREATE INDEX ix_thermal_board_at ON thermal_samples (board, at);
