-- An append only record of who did what.

CREATE TABLE audit (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    actor   VARCHAR(64)  NOT NULL,
    action  VARCHAR(32)  NOT NULL,
    subject VARCHAR(64)  DEFAULT '' NOT NULL,
    detail  VARCHAR(240) DEFAULT '' NOT NULL,
    key_id  VARCHAR(32)  DEFAULT '' NOT NULL,
    CONSTRAINT pk_audit PRIMARY KEY (id),
    CONSTRAINT ck_audit_action CHECK (LENGTH(action) > 0)
);
CREATE INDEX ix_audit_at ON audit (at);
CREATE INDEX ix_audit_subject ON audit (subject);
CREATE INDEX ix_audit_actor ON audit (actor);
