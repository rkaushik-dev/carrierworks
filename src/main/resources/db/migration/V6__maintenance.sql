-- The log of who worked on which board and when.

CREATE TABLE maintenance (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY,
    board          VARCHAR(12)  NOT NULL,
    kind           VARCHAR(24)  NOT NULL,
    at             TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    by             VARCHAR(64)  NOT NULL,
    notes          VARCHAR(240) DEFAULT '' NOT NULL,
    faults_cleared INTEGER DEFAULT 0 NOT NULL,
    CONSTRAINT pk_maintenance PRIMARY KEY (id),
    CONSTRAINT fk_maintenance_board FOREIGN KEY (board) REFERENCES boards (tag) ON DELETE CASCADE,
    CONSTRAINT ck_maintenance_faults CHECK (faults_cleared >= 0)
);
CREATE INDEX ix_maintenance_board_at ON maintenance (board, at);
CREATE INDEX ix_maintenance_kind ON maintenance (kind);
